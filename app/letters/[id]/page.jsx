export async function generateMetadata({ params }) {
  const { id } = await params;
  const letter = letters.find((item) => item.id === id);

  return {
    title: letter ? `${letter.title} | Ganzhe & Lulu` : "Letter | Ganzhe & Lulu"
  };
}

